export function getNlsGuideByGradeAndSchoolEn(grade: string, schoolType: SchoolType): { level: 'CB1' | 'CB2' | 'TC1' | 'TC2' | 'NC1'; guideText: string } {
  const gNum = parseInt(grade.replace(/\D/g, ''), 10) || 8;

  // PRIMARY: Grades 1, 2, 3 -> CB1; Grades 4, 5 -> CB2
  if (gNum <= 3 || (schoolType === 'primary' && gNum <= 3)) {
    return { level: 'CB1', guideText: DIGITAL_COMPETENCY_GUIDE_CB1_EN };
  }
  if (gNum <= 5 || schoolType === 'primary') {
    return { level: 'CB2', guideText: DIGITAL_COMPETENCY_GUIDE_CB2_EN };
  }

  // LOWER SECONDARY: Grades 6, 7 -> TC1; Grades 8, 9 -> TC2
  if (gNum <= 7 || (schoolType === 'secondary' && gNum <= 7)) {
    return { level: 'TC1', guideText: DIGITAL_COMPETENCY_GUIDE_TC1_EN };
  }
  if (gNum <= 9 || schoolType === 'secondary') {
    return { level: 'TC2', guideText: DIGITAL_COMPETENCY_GUIDE_TC2_EN };
  }

  // UPPER SECONDARY: Grades 10, 11, 12 -> NC1
  return { level: 'NC1', guideText: DIGITAL_COMPETENCY_GUIDE_NC1_EN };
}

export interface LessonNlsContextEn {
  lessonName?: string;
  topic?: string;
  yccd?: string;
  subject?: string;
  lessonIndex?: number;
}

export function getNlsCodeForEnglishLesson(
  grade: string,
  schoolType: SchoolType,
  contextOrIndex: number | LessonNlsContextEn | string
): { code: string; level: string; requirement: string } {
  const { level, guideText } = getNlsGuideByGradeAndSchoolEn(grade, schoolType);
  const lines = guideText.split('\n').filter((l) => l.startsWith('- **Code:'));
  
  // Extract all available items for this grade level
  const items: Array<{ code: string; requirement: string; raw: string }> = [];
  for (const line of lines) {
    const match = line.match(/- \*\*Code:\s*([^*]+)\*\*\s*-\s*RLO:\s*(.+)$/);
    if (match) {
      items.push({
        code: match[1].trim(),
        requirement: match[2].trim(),
        raw: line
      });
    }
  }

  if (items.length === 0) {
    const fallbackCode = level === 'CB1' ? '1.1.CB1a' : level === 'CB2' ? '1.1.CB2b' : level === 'TC1' ? '1.1.TC1b' : level === 'TC2' ? '1.1.TC2b' : '1.1.NC1b';
    return {
      code: fallbackCode,
      level,
      requirement: 'Search and exploit digital resources for English language learning tasks'
    };
  }

  // Helper to find item by code prefix
  const findByCodePrefix = (prefix: string): { code: string; requirement: string } | null => {
    const found = items.find((it) => it.code.startsWith(prefix));
    if (found) return { code: found.code, requirement: found.requirement };
    return null;
  };

  // Helper to find item by domain
  const findByDomain = (domainDigit: string): { code: string; requirement: string } | null => {
    const matched = items.filter((it) => it.code.startsWith(`${domainDigit}.`));
    if (matched.length > 0) {
      return { code: matched[0].code, requirement: matched[0].requirement };
    }
    return null;
  };

  // Extract contextual text
  let contextText = '';
  let lessonName = '';
  let lessonIdx = 0;

  if (typeof contextOrIndex === 'number') {
    lessonIdx = contextOrIndex;
  } else if (typeof contextOrIndex === 'string') {
    contextText = contextOrIndex.toLowerCase();
    lessonName = contextText;
  } else if (contextOrIndex && typeof contextOrIndex === 'object') {
    const ctx = contextOrIndex as LessonNlsContextEn;
    lessonName = (ctx.lessonName || '').toLowerCase();
    contextText = `${ctx.lessonName || ''} ${ctx.topic || ''} ${ctx.yccd || ''} ${ctx.subject || ''}`.toLowerCase();
    if (typeof ctx.lessonIndex === 'number') {
      lessonIdx = ctx.lessonIndex;
    }
  }

  // 1. Prioritize Lesson Type if lessonName is available
  if (lessonName.includes('getting started')) {
    const res = findByCodePrefix('1.1.') || findByDomain('1');
    if (res) return { ...res, level };
  }
  if (lessonName.includes('closer look 1')) {
    const res = findByCodePrefix('1.2.') || findByDomain('1');
    if (res) return { ...res, level };
  }
  if (lessonName.includes('closer look 2')) {
    const res = findByCodePrefix('1.3.') || findByDomain('1');
    if (res) return { ...res, level };
  }
  if (lessonName.includes('communication')) {
    const res = findByCodePrefix('2.1.') || findByDomain('2');
    if (res) return { ...res, level };
  }
  if (lessonName.includes('skills 1')) {
    const res = findByCodePrefix('2.2.') || findByDomain('2');
    if (res) return { ...res, level };
  }
  if (lessonName.includes('skills 2')) {
    const res = findByCodePrefix('3.1.') || findByDomain('3');
    if (res) return { ...res, level };
  }
  if (lessonName.includes('looking back') || lessonName.includes('project')) {
    const res = (level === 'TC1' && lessonIdx % 2 === 1 ? findByCodePrefix('3.3.') : null) || findByCodePrefix('2.4.') || findByDomain('2');
    if (res) return { ...res, level };
  }
  if (lessonName.includes('language') && (lessonName.includes('review') || contextText.includes('review'))) {
    const res = findByCodePrefix('5.2.') || findByDomain('5');
    if (res) return { ...res, level };
  }
  if (lessonName.includes('skills') && (lessonName.includes('review') || contextText.includes('review'))) {
    const res = findByCodePrefix('3.2.') || findByDomain('3');
    if (res) return { ...res, level };
  }
  if (lessonName.includes('test') || lessonName.includes('exam')) {
    const res = findByCodePrefix('4.2.') || findByDomain('4');
    if (res) return { ...res, level };
  }
  if (lessonName.includes('feedback')) {
    const res = findByCodePrefix('5.1.') || findByDomain('5');
    if (res) return { ...res, level };
  }
  if (lessonName.includes('reserve')) {
    const res = findByCodePrefix('2.5.') || findByCodePrefix('6.2.') || findByDomain('2');
    if (res) return { ...res, level };
  }

  // 2. Secondary General Context Match
  if (
    contextText.includes('test') ||
    contextText.includes('exam') ||
    contextText.includes('assessment') ||
    contextText.includes('kiểm tra') ||
    contextText.includes('đánh giá')
  ) {
    const res = findByCodePrefix('4.2.') || findByDomain('4');
    if (res) return { ...res, level };
  }

  if (
    contextText.includes('project') ||
    contextText.includes('presentation') ||
    contextText.includes('groupwork')
  ) {
    const res = findByCodePrefix('2.4.') || findByDomain('2');
    if (res) return { ...res, level };
  }

  if (
    contextText.includes('writing') ||
    contextText.includes('poster') ||
    contextText.includes('slides') ||
    contextText.includes('design')
  ) {
    const res = findByCodePrefix('3.1.') || findByDomain('3');
    if (res) return { ...res, level };
  }

  if (
    contextText.includes('pronunciation') ||
    contextText.includes('phonics') ||
    contextText.includes('dictionary') ||
    contextText.includes('vocabulary')
  ) {
    const res = findByCodePrefix('1.2.') || findByDomain('1');
    if (res) return { ...res, level };
  }

  // 3. Fallback smart rotation
  const domainSequence = ['1.1.', '2.1.', '3.1.', '1.2.', '2.4.', '5.2.', '4.1.', '3.2.', '6.2.', '2.5.'];
  const targetPrefix = domainSequence[lessonIdx % domainSequence.length];
  const matchedItem = items.find((it) => it.code.startsWith(targetPrefix)) || items[lessonIdx % items.length];

  return {
    code: matchedItem.code,
    level,
    requirement: matchedItem.requirement
  };
}

/**
 * Tra cứu nội dung yêu cầu cần đạt (RLO) của một mã NLS (CV 3456) theo mã code
 */
export function lookupNlsRequirementEn(code: string): string | null {
  const allGuides = [
    DIGITAL_COMPETENCY_GUIDE_CB1_EN,
    DIGITAL_COMPETENCY_GUIDE_CB2_EN,
    DIGITAL_COMPETENCY_GUIDE_TC1_EN,
    DIGITAL_COMPETENCY_GUIDE_TC2_EN,
    DIGITAL_COMPETENCY_GUIDE_NC1_EN
  ].join('\n');

  const cleanCode = code.replace(/[^a-zA-Z0-9\.]/g, '').toLowerCase();
  const lines = allGuides.split('\n').filter((l) => l.startsWith('- **Code:'));

  for (const line of lines) {
    const match = line.match(/- \*\*Code:\s*([^*]+)\*\*\s*-\s*RLO:\s*(.+)$/);
    if (match) {
      const lineCode = match[1].replace(/[^a-zA-Z0-9\.]/g, '').toLowerCase();
      if (lineCode === cleanCode) {
        return match[2].trim();
      }
    }
  }

  // Prefix fallback
  for (const line of lines) {
    const match = line.match(/- \*\*Code:\s*([^*]+)\*\*\s*-\s*RLO:\s*(.+)$/);
    if (match) {
      const lineCode = match[1].replace(/[^a-zA-Z0-9\.]/g, '').toLowerCase();
      if (lineCode.startsWith(cleanCode) || cleanCode.startsWith(lineCode)) {
        return match[2].trim();
      }
    }
  }

  return null;
}


