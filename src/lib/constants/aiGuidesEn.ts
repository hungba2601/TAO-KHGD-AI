export interface LessonAiContextEn {
  lessonName?: string;
  topic?: string;
  yccd?: string;
  subject?: string;
  lessonIndex?: number;
}

export function getAiCodeForEnglishLesson(
  grade: string,
  contextOrIndex: number | LessonAiContextEn | string
): { code: string; title: string; requirement: string } {
  const g = grade.trim();
  const guideStr = AI_GUIDES_EN[g] || AI_GUIDES_EN['8'];
  const lines = guideStr.split('\n').filter((l) => l.startsWith('• CODE'));
  
  // Extract all AI items for this grade
  const items: Array<{ code: string; title: string; requirement: string }> = [];
  for (const line of lines) {
    const match = line.match(/• CODE\s+([^:]+)\s*:\s*([^R]+?)\s*REQUIREMENT:\s*(.+)$/);
    if (match) {
      items.push({
        code: match[1].trim(),
        title: match[2].trim(),
        requirement: match[3].trim()
      });
    }
  }

  if (items.length === 0) {
    return {
      code: `${g}.C1.1`,
      title: 'AI in Language Learning',
      requirement: 'Utilize AI language tools to practice vocabulary, pronunciation, and listening comprehension.'
    };
  }

  // Extract contextual text
  let contextText = '';
  let lessonName = '';
  let lessonIdx = 0;

  if (typeof contextOrIndex === 'number') {
    lessonIdx = contextOrIndex;
  } else if (typeof contextOrIndex === 'string') {
    contextText = contextOrIndex.toLowerCase();
    lessonName = contextText;
  } else if (contextOrIndex && typeof contextOrIndex === 'object') {
    const ctx = contextOrIndex as LessonAiContextEn;
    lessonName = (ctx.lessonName || '').toLowerCase();
    contextText = `${ctx.lessonName || ''} ${ctx.topic || ''} ${ctx.yccd || ''} ${ctx.subject || ''}`.toLowerCase();
    if (typeof ctx.lessonIndex === 'number') {
      lessonIdx = ctx.lessonIndex;
    }
  }

  // Helpers to find item by topic letter (A, B, C, D)
  const findByTopic = (topicLetter: 'A' | 'B' | 'C' | 'D'): { code: string; title: string; requirement: string } | null => {
    const found = items.filter((it) => it.code.includes(`.${topicLetter}`));
    if (found.length > 0) {
      return found[lessonIdx % found.length];
    }
    return null;
  };

  const findByCode = (codePrefix: string): { code: string; title: string; requirement: string } | null => {
    const found = items.find((it) => it.code.startsWith(codePrefix));
    if (found) return found;
    return null;
  };

  // 1. Prioritize Lesson Type if lessonName is available
  if (lessonName.includes('getting started')) {
    const res = findByCode(`${g}.C2`) || findByTopic('C') || findByTopic('A');
    if (res) return res;
  }
  if (lessonName.includes('closer look 1')) {
    const res = findByCode(`${g}.C3`) || findByCode(`${g}.C1`) || findByTopic('C');
    if (res) return res;
  }
  if (lessonName.includes('closer look 2')) {
    const res = findByCode(`${g}.C1`) || findByCode(`${g}.C5`) || findByTopic('C') || findByTopic('A');
    if (res) return res;
  }
  if (lessonName.includes('communication')) {
    const res = findByCode(`${g}.D2`) || findByCode(`${g}.C2`) || findByTopic('C');
    if (res) return res;
  }
  if (lessonName.includes('skills 1')) {
    const res = findByCode(`${g}.A1`) || findByCode(`${g}.C1`) || findByTopic('A');
    if (res) return res;
  }
  if (lessonName.includes('skills 2')) {
    const res = findByCode(`${g}.B3`) || findByCode(`${g}.A1`) || findByTopic('B') || findByTopic('C');
    if (res) return res;
  }
  if (lessonName.includes('looking back') || lessonName.includes('project')) {
    const res = findByCode(`${g}.D1`) || findByTopic('D');
    if (res) return res;
  }
  if (lessonName.includes('language') && (lessonName.includes('review') || contextText.includes('review'))) {
    const res = findByCode(`${g}.C1`) || findByCode(`${g}.A3`) || findByTopic('C');
    if (res) return res;
  }
  if (lessonName.includes('skills') && (lessonName.includes('review') || contextText.includes('review'))) {
    const res = findByCode(`${g}.C3`) || findByCode(`${g}.C2`) || findByTopic('C');
    if (res) return res;
  }
  if (lessonName.includes('test') || lessonName.includes('exam')) {
    const res = findByCode(`${g}.A3`) || findByCode(`${g}.B1`) || findByTopic('B');
    if (res) return res;
  }
  if (lessonName.includes('feedback')) {
    const res = findByCode(`${g}.A1`) || findByCode(`${g}.A2`) || findByTopic('A');
    if (res) return res;
  }
  if (lessonName.includes('reserve')) {
    const res = findByCode(`${g}.C2`) || findByCode(`${g}.D1`) || findByTopic('C');
    if (res) return res;
  }

  // 2. Projects, Systems, Problem Solving (Topic D)
  if (
    contextText.includes('project') ||
    contextText.includes('stem') ||
    contextText.includes('solution')
  ) {
    const res = findByTopic('D') || findByTopic('C');
    if (res) return res;
  }

  // 3. Ethics, Safety, Assessments, Review, Academic Integrity (Topic B)
  if (
    contextText.includes('ethics') ||
    contextText.includes('safe') ||
    contextText.includes('privacy') ||
    contextText.includes('test') ||
    contextText.includes('exam')
  ) {
    const res = findByTopic('B') || findByTopic('A');
    if (res) return res;
  }

  // 4. Fallback rotation
  const topicRotation: Array<'C' | 'A' | 'C' | 'B' | 'D'> = ['C', 'A', 'C', 'B', 'D'];
  const targetTopic = topicRotation[lessonIdx % topicRotation.length];
  const matched = findByTopic(targetTopic) || items[lessonIdx % items.length];

  return matched;
}

/**
 * Tra cứu nội dung yêu cầu của một mã AI (QĐ 2422) theo mã code (ví dụ: 6.A1.1, 6.C3.1...)
 */
export function lookupAiRequirementEn(code: string): { title: string; requirement: string } | null {
  const cleanCode = code.replace(/[^a-zA-Z0-9\.]/g, '').toLowerCase();

  for (const gradeKey in AI_GUIDES_EN) {
    const guide = AI_GUIDES_EN[gradeKey];
    const lines = guide.split('\n').filter((l) => l.startsWith('• CODE'));

    for (const line of lines) {
      const match = line.match(/• CODE\s+([^:]+)\s*:\s*([^R]+?)\s*REQUIREMENT:\s*(.+)$/);
      if (match) {
        const itemCode = match[1].replace(/[^a-zA-Z0-9\.]/g, '').toLowerCase();
        if (itemCode === cleanCode) {
          return {
            title: match[2].trim(),
            requirement: match[3].trim()
          };
        }
      }
    }
  }

  // Prefix fallback (e.g. 6.C3 or 6.C3.1)
  for (const gradeKey in AI_GUIDES_EN) {
    const guide = AI_GUIDES_EN[gradeKey];
    const lines = guide.split('\n').filter((l) => l.startsWith('• CODE'));

    for (const line of lines) {
      const match = line.match(/• CODE\s+([^:]+)\s*:\s*([^R]+?)\s*REQUIREMENT:\s*(.+)$/);
      if (match) {
        const itemCode = match[1].replace(/[^a-zA-Z0-9\.]/g, '').toLowerCase();
        if (itemCode.startsWith(cleanCode) || cleanCode.startsWith(itemCode)) {
          return {
            title: match[2].trim(),
            requirement: match[3].trim()
          };
        }
      }
    }
  }

  return null;
}


